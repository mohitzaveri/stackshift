import { REPORT_TITLES, type AnalysisResult, type RepoFacts, type ReportId } from "./types";

export const REPORT_ORDER: ReportId[] = ["stack", "research", "estimate", "plan"];

/** "owner/repo", or "owner/repo/apps/web" when one folder was analyzed. */
export function repoLabel(repo: Pick<RepoFacts, "owner" | "name"> & { path?: string | null }): string {
  return `${repo.owner}/${repo.name}${repo.path ? `/${repo.path}` : ""}`;
}

/** The requested model, plus any fallback models that answered a step. */
export function modelLabel(result: AnalysisResult): string {
  const fallbacks = (result.servedBy ?? []).filter((model) => model !== result.model);
  return fallbacks.length ? `${result.model} (with fallback ${fallbacks.join(", ")})` : result.model;
}

export function reportFileName(result: AnalysisResult, part: ReportId | "full"): string {
  const slug = repoLabel(result.repo).toLowerCase().replace(/[^a-z0-9-]+/g, "-");
  return `${slug}-${part === "full" ? "migration-report" : part}.md`;
}

/** One Markdown document with all four reports, for download. */
export function buildFullReport(result: AnalysisResult): string {
  const header = [
    `# Migration report: ${repoLabel(result.repo)} → ${result.targetStack}`,
    "",
    `- Repository: ${result.repo.url}`,
    `- Generated: ${new Date(result.createdAt).toUTCString()}`,
    `- Generated by StackShift${result.demo ? " in demo mode (no AI)" : ` with ${modelLabel(result)}`}`,
  ];
  const sections = REPORT_ORDER.map((id, index) => `# ${index + 1}. ${REPORT_TITLES[id]}\n\n${result.reports[id]}`);
  return [header.join("\n"), ...sections].join("\n\n---\n\n") + "\n";
}

export function downloadText(fileName: string, text: string): void {
  const url = URL.createObjectURL(new Blob([text], { type: "text/markdown;charset=utf-8" }));
  const link = document.createElement("a");
  link.href = url;
  link.download = fileName;
  link.click();
  // Revoking right away can cancel the download in some browsers.
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
