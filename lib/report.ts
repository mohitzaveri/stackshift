import { REPORT_TITLES, type AnalysisResult, type ReportId } from "./types";

export const REPORT_ORDER: ReportId[] = ["stack", "research", "estimate", "plan"];

export function reportFileName(result: AnalysisResult, part: ReportId | "full"): string {
  const slug = `${result.repo.owner}-${result.repo.name}`.toLowerCase().replace(/[^a-z0-9-]+/g, "-");
  return `${slug}-${part === "full" ? "migration-report" : part}.md`;
}

/** One Markdown document with all four reports, for download. */
export function buildFullReport(result: AnalysisResult): string {
  const header = [
    `# Migration report: ${result.repo.owner}/${result.repo.name} → ${result.targetStack}`,
    "",
    `- Repository: ${result.repo.url}`,
    `- Generated: ${new Date(result.createdAt).toUTCString()}`,
    `- Generated by StackShift${result.demo ? " in demo mode (no AI)" : ` with ${result.model}`}`,
  ];
  const sections = REPORT_ORDER.map((id, index) => `# ${index + 1}. ${REPORT_TITLES[id]}\n\n${result.reports[id]}`);
  return [header.join("\n"), ...sections].join("\n\n---\n\n") + "\n";
}

export function downloadText(fileName: string, text: string): void {
  const url = URL.createObjectURL(new Blob([text], { type: "text/markdown;charset=utf-8" }));
  const link = document.createElement("a");
  link.href = url;
  link.download = fileName;
  link.click();
  // Revoking right away can cancel the download in some browsers.
  setTimeout(() => URL.revokeObjectURL(url), 1000);
}
